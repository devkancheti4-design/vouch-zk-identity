/**
 * Derives the issuer's public key at BUILD time, so the serverless /api/issuer never loads a
 * curve implementation to answer a question whose answer is fixed.
 *
 * The key is a pure function of ISSUER_SECRET, so computing it once here is exactly as correct
 * as computing it on every cold start -- and it cannot fail in a runtime we do not control.
 */
import { buildEddsa, buildPoseidon } from "circomlibjs";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const LABEL = process.env.ISSUER_LABEL ?? "Demo KYC Provider";
const SECRET = process.env.ISSUER_SECRET ?? LABEL;

const eddsa = await buildEddsa();
const poseidon = await buildPoseidon();
const F = poseidon.F;
const priv = createHash("sha256").update(SECRET).digest();
const [Ax, Ay] = eddsa.prv2pub(priv);

// Write the WHOLE endpoint, with the key inlined.
//
// /api/health imports nothing but types and works; every version of /api/issuer that imported
// a local relative module crashed, including one that imported only a generated constant. The
// functions glob is "api/*.ts", which does not match api/generated/*.ts, so that helper was
// very likely never deployed at all. Generating a self-contained file removes the question.
writeFileSync("api/issuer.ts",
  `import type { VercelRequest, VercelResponse } from "@vercel/node";\n\n` +
  `/**\n` +
  ` * GENERATED by scripts/gen-issuer-key.mjs -- do not edit.\n` +
  ` *\n` +
  ` * Who is vouching. The key is a pure function of ISSUER_SECRET, so it is derived at build\n` +
  ` * time and inlined here: this endpoint imports nothing but types, loads no curve, and has\n` +
  ` * nothing that can fail at cold start.\n` +
  ` */\n` +
  `export default function handler(_req: VercelRequest, res: VercelResponse) {\n` +
  `  res.setHeader("Access-Control-Allow-Origin", "*");\n` +
  `  res.status(200).json({\n` +
  `    name: ${JSON.stringify(LABEL)},\n` +
  `    pubX: ${JSON.stringify(F.toObject(Ax).toString())},\n` +
  `    pubY: ${JSON.stringify(F.toObject(Ay).toString())},\n` +
  `    issuedCount: 0,\n` +
  `  });\n` +
  `}\n`);
console.log("wrote api/issuer.ts with the key inlined for", LABEL);

const c = globalThis.curve_bn128;
if (c?.terminate) await c.terminate();
